#!/usr/bin/env python3
"""Build a conservative provenance register from a Git tree snapshot.

This records evidence-backed project-level attribution, not authorship inferred
from style, line count, or Git author metadata. It never executes repository files.
"""
from __future__ import annotations

import argparse
import csv
import subprocess
from pathlib import Path


FIELDS = [
    "path", "category", "git_blob_sha", "origin_classification", "known_ai_role",
    "evidence_type", "concrete_evidence", "confidence", "limitations",
    "review_or_execution_provenance", "public_authorship_statement_supported",
]


def git(*args: str) -> bytes:
    return subprocess.check_output(["git", *args])


def classify(path: str) -> dict[str, str]:
    suffix = Path(path).suffix.lower()
    if path.startswith("results/raw/"):
        return dict(category="raw test/tool output", origin_classification="TOOL_GENERATED",
                    known_ai_role="Codex-assisted test orchestration is documented; the operator for each run is not consistently identified.",
                    evidence_type="artifact records and run metadata", concrete_evidence="results/processed/* summaries and run manifests identify producing tools/commands where captured.", confidence="HIGH for tool-generated bytes; LOW for human operator",
                    limitations="Generated output does not establish who launched the command or independently inspected the result.",
                    review_or_execution_provenance="Per-run metadata varies.", public_authorship_statement_supported="No personal execution claim from this classification.")
    if path.startswith("portfolio_audit/generated/"):
        return dict(category="generated audit data", origin_classification="TOOL_GENERATED",
                    known_ai_role="Created in the Codex-assisted audit workflow.", evidence_type="generator script and audit commit history", concrete_evidence="portfolio_audit/build_ai_provenance_register.py generates this register; portfolio_audit/build_register.py and portfolio_audit/build_semantic_review.py generate earlier audit inventories.", confidence="HIGH for generated status",
                    limitations="The register records generation, not personal review or authorship of source files.", review_or_execution_provenance="Audit generation is documented in the associated PR/task records.", public_authorship_statement_supported="No individual source authorship claim.")
    if path.startswith(("rtl/", "formal/", "tb/", "bench/", "scripts/", "smoke/", "constraints/")) or path == "requirements/requirements.txt":
        return dict(category="engineering source/configuration", origin_classification="AI_ASSISTED_CONFIRMED",
                    known_ai_role="Project records document substantial ChatGPT/Codex planning, implementation, test drafting, debugging, automation and review assistance across the engineering workflow.",
                    evidence_type="operating instructions, task history, merged PR descriptions and source review", concrete_evidence="01_CHATGPT_PROJECT_OPERATING_INSTRUCTIONS.md; docs/history/; PRs #1–#6; portfolio_audit/semantic_source_review.csv.", confidence="MEDIUM at project/source-set level",
                    limitations="Exact file/line authorship split is not preserved. This does not establish which lines were written by a person or model.",
                    review_or_execution_provenance="The semantic review shows files were examined; it does not show who authored them or who personally ran every test.", public_authorship_statement_supported="May state that the project was developed with substantial ChatGPT/Codex assistance; no per-file manual-authorship claim is supported.")
    if path.startswith(("docs/", "results/processed/")) or path in ("README.md", "00_MASTER_PROJECT_PLAN.md", "01_CHATGPT_PROJECT_OPERATING_INSTRUCTIONS.md", "04_MASTER_CHECKLIST.md", "AGENTS.md"):
        return dict(category="technical/project documentation", origin_classification="AI_ASSISTED_CONFIRMED",
                    known_ai_role="Documentation was created or revised in a project workflow that explicitly assigns substantial planning, drafting, review and execution work to ChatGPT/Codex.",
                    evidence_type="document history, task instructions and merged PR descriptions", concrete_evidence="01_CHATGPT_PROJECT_OPERATING_INSTRUCTIONS.md; docs/history/; PR descriptions #1–#6.", confidence="MEDIUM",
                    limitations="Path-level Git history cannot reliably separate owner wording, model drafts and later edits.",
                    review_or_execution_provenance="Some reports include tool logs or model review; this is not independent human review.", public_authorship_statement_supported="May describe the documentation as AI-assisted, not wholly human- or AI-authored.")
    return dict(category="project/admin/other", origin_classification="UNKNOWN",
                known_ai_role="No file-specific role is established by available records.", evidence_type="repository-level history only", concrete_evidence="No direct file-level provenance located.", confidence="LOW",
                limitations="Git author identity and style are not proof of manual or model authorship.",
                review_or_execution_provenance="Not established.", public_authorship_statement_supported="No file-specific authorship statement supported.")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--revision", default="HEAD", help="Git tree revision to inventory")
    parser.add_argument("--output", default="portfolio_audit/generated/ai_provenance_register.csv")
    args = parser.parse_args()
    rev = git("rev-parse", args.revision).decode().strip()
    records = git("ls-tree", "-rz", "--full-tree", rev).split(b"\0")
    rows = []
    for record in records:
        if not record:
            continue
        meta, raw_path = record.split(b"\t", 1)
        mode, kind, oid = meta.decode().split()
        path = raw_path.decode("utf-8", "surrogateescape")
        if kind != "blob":
            continue
        row = {"path": path, "category": "", "git_blob_sha": oid}
        row.update(classify(path))
        rows.append(row)
    rows.sort(key=lambda row: row["path"])
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=FIELDS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    print(f"revision={rev} files={len(rows)} output={output}")


if __name__ == "__main__":
    main()
